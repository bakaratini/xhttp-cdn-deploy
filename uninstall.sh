#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'
umask 077

APP_NAME="xhttp-cdn-deploy"
STATE_DIR="/etc/${APP_NAME}"
LOCK_FILE="/run/lock/${APP_NAME}.lock"
INSTALL_STATE_FILE="${STATE_DIR}/install-state.env"
XRAY_CONFIG_PATH="/usr/local/etc/xray/config.json"
NGINX_CONF_PATH="/etc/nginx/conf.d/${APP_NAME}.conf"
CLIENT_FILE="/root/${APP_NAME}/client-v2rayn.txt"
CLIENT_DIR="/root/${APP_NAME}"
SITE_DIR="/var/www/${APP_NAME}"
ACME_HOME="/root/.acme.sh"
DRY_RUN=0
ASSUME_YES=0
TEST_ROOT="${XHTTP_UNINSTALL_TEST_ROOT:-}"
TMP_DIR=""
RETAINED_RESOURCES=()
FILE_PRESERVED=0
PRESERVE_NGINX=0
PRESERVE_TLS=0
PRESERVE_ACME=0
XRAY_REMOVED=0
PRESERVE_XRAY=0

log() { printf '[INFO] %s\n' "$*"; }
warn() { printf '[WARN] %s\n' "$*" >&2; }
die() { printf '[ERROR] %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'EOF'
Usage:
  sudo bash uninstall.sh [--dry-run] [--yes]

Without --yes, the script asks for the word UNINSTALL before making changes.
Cloudflare DNS records and firewall rules are not changed.
EOF
}

parse_args() {
  while (($#)); do
    case "$1" in
      --dry-run) DRY_RUN=1 ;;
      --yes|-y) ASSUME_YES=1 ;;
      --help|-h) usage; exit 0 ;;
      *) usage >&2; die "unknown argument: $1" ;;
    esac
    shift
  done
}

path_of() {
  local value="$1"
  if [[ -n "$TEST_ROOT" ]]; then
    printf '%s%s' "${TEST_ROOT%/}" "$value"
  else
    printf '%s' "$value"
  fi
}

require_root() {
  if [[ -n "$TEST_ROOT" ]]; then
    [[ "${XHTTP_UNINSTALL_TEST_MODE:-0}" == 1 ]] || die "test root is only available to the isolated test harness"
    [[ "$TEST_ROOT" == /* && "$TEST_ROOT" != / ]] || die "invalid test root"
  elif (( EUID != 0 )); then
    die "run this script as root"
  fi
}

load_state() {
  local state_path
  state_path="$(path_of "$INSTALL_STATE_FILE")"
  [[ -f "$state_path" ]] || die "installation ownership state is missing; refusing to remove system files"
  if [[ -z "$TEST_ROOT" && "$(stat -c '%u' "$state_path")" != 0 ]]; then
    die "installation ownership state is not owned by root"
  fi
  # This root-owned file is generated by deploy.sh using shell-escaped values.
  # shellcheck disable=SC1090
  . "$state_path"
  [[ "${STATE_VERSION:-}" == 3 ]] || die "unsupported installation state version"
  [[ "${XRAY_INSTALLED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid Xray ownership marker"
  [[ -z "${XRAY_INSTALLER_COMMIT:-}" || "${XRAY_INSTALLER_COMMIT}" =~ ^[0-9a-f]{40}$ ]] ||
    die "invalid Xray installer commit in state"
  if (( XRAY_INSTALLED_BY_TOOL )); then
    [[ "${XRAY_INSTALLER_COMMIT:-}" =~ ^[0-9a-f]{40}$ ]] ||
      die "Xray installer commit is required for an installed Xray component"
  fi
  [[ "${ACME_INSTALLED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid acme.sh ownership marker"
  [[ "${ACME_CERT_ISSUED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid certificate ownership marker"
  [[ "${SITE_DIR_CREATED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid site ownership marker"
  [[ "${SITE_INDEX_CREATED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid site file ownership marker"
}

show_plan() {
  printf 'The following tool-managed resources will be removed or restored:\n'
  (( XRAY_INSTALLED_BY_TOOL )) && printf '  Xray service, binary, data, logs, and tool configuration\n'
  printf '  Nginx configuration: %s\n' "$NGINX_CONF_PATH"
  printf '  Client link and tool-created site files\n'
  printf '  Local state, certificate copies, and saved deployment credentials\n'
  (( ACME_CERT_ISSUED_BY_TOOL )) && printf '  ACME certificate lineage for %s\n' "${ACME_DOMAIN:-unknown}"
  [[ -n "${OWNED_PACKAGES:-}" ]] && printf '  Newly installed Debian packages, subject to dependency checks\n'
  printf 'Cloudflare DNS records and firewall rules will remain unchanged.\n'
}

new_temp_dir() {
  local base
  if [[ -d /srv/paseo/cache ]]; then
    base=/srv/paseo/cache
  else
    base="${TMPDIR:-/tmp}"
  fi
  TMP_DIR="$(mktemp -d "${base%/}/${APP_NAME}-uninstall.XXXXXX")"
}

restore_or_remove_file() {
  local destination="$1"
  local backup="$2"
  local created_by_tool="${3:-1}"
  local expected_hash="${4:-}"
  local dest_path backup_path current_hash
  FILE_PRESERVED=0
  dest_path="$(path_of "$destination")"
  backup_path=""
  [[ -z "$backup" ]] || backup_path="$(path_of "$backup")"
  if [[ -L "$dest_path" ]]; then
    warn "$destination is now a symlink; preserving it"
    FILE_PRESERVED=1
    RETAINED_RESOURCES+=("$destination (changed after deployment)")
    return 0
  fi
  if [[ -e "$dest_path" ]]; then
    if [[ ! "$expected_hash" =~ ^[0-9a-f]{64}$ ]]; then
      warn "no deployment hash is available for $destination; preserving it"
      FILE_PRESERVED=1
      RETAINED_RESOURCES+=("$destination (ownership could not be verified)")
      return 0
    fi
    current_hash="$(sha256sum "$dest_path" | awk '{print $1}')"
    if [[ "$current_hash" != "$expected_hash" ]]; then
      warn "$destination changed after deployment; preserving it"
      FILE_PRESERVED=1
      RETAINED_RESOURCES+=("$destination (changed after deployment)")
      return 0
    fi
  fi
  if [[ -n "$backup_path" && -e "$backup_path" ]]; then
    install -d -m 755 "$(dirname "$dest_path")"
    cp -a "$backup_path" "$dest_path"
    log "restored $destination"
  elif [[ "$created_by_tool" == 1 && -e "$dest_path" ]]; then
    rm -f "$dest_path"
    log "removed $destination"
  fi
}

xray_is_safe_to_remove() {
  local config_path config_dir current_hash extra service_path service_hash binary_path binary_hash dropin
  config_path="$(path_of "$XRAY_CONFIG_PATH")"
  config_dir="$(dirname "$config_path")"
  if [[ -e "$config_path" ]]; then
    if [[ -L "$config_path" || ! -f "$config_path" || \
          ! "${XRAY_CONFIG_SHA256:-}" =~ ^[0-9a-f]{64}$ ]]; then
      warn "Xray configuration ownership could not be verified; preserving Xray"
      return 1
    fi
    current_hash="$(sha256sum "$config_path" | awk '{print $1}')"
    if [[ "$current_hash" != "$XRAY_CONFIG_SHA256" ]]; then
      warn "Xray configuration changed after deployment; preserving Xray"
      return 1
    fi
  fi
  if [[ -d "$config_dir" ]]; then
    extra="$(find "$config_dir" -mindepth 1 -maxdepth 1 ! -name config.json -print -quit)"
    if [[ -n "$extra" ]]; then
      warn "additional Xray configuration files exist; preserving Xray"
      return 1
    fi
  fi
  binary_path="$(path_of /usr/local/bin/xray)"
  if [[ -e "$binary_path" || -L "$binary_path" ]]; then
    if [[ -L "$binary_path" || ! -f "$binary_path" || \
          ! "${XRAY_BINARY_SHA256:-}" =~ ^[0-9a-f]{64}$ ]]; then
      warn "Xray binary ownership could not be verified; preserving Xray"
      return 1
    fi
    binary_hash="$(sha256sum "$binary_path" | awk '{print $1}')"
    if [[ "$binary_hash" != "$XRAY_BINARY_SHA256" ]]; then
      warn "Xray binary changed after deployment; preserving Xray"
      return 1
    fi
  fi
  service_path="${XRAY_SERVICE_FILE:-}"
  if [[ -n "$service_path" ]]; then
    service_path="$(path_of "$service_path")"
    if [[ -e "$service_path" ]]; then
      if [[ -L "$service_path" || ! "${XRAY_SERVICE_SHA256:-}" =~ ^[0-9a-f]{64}$ ]]; then
        warn "Xray service ownership could not be verified; preserving Xray"
        return 1
      fi
      service_hash="$(sha256sum "$service_path" | awk '{print $1}')"
      if [[ "$service_hash" != "$XRAY_SERVICE_SHA256" ]]; then
        warn "Xray service changed after deployment; preserving Xray"
        return 1
      fi
    fi
  fi
  for dropin in /etc/systemd/system/xray.service.d /etc/systemd/system/xray@.service.d; do
    dropin="$(path_of "$dropin")"
    if [[ -d "$dropin" ]] && find "$dropin" -type f -print -quit | grep -q .; then
      warn "Xray systemd overrides exist; preserving Xray"
      return 1
    fi
  done
  return 0
}

nginx_is_safe_to_remove() {
  local config_path current_hash
  config_path="$(path_of "$NGINX_CONF_PATH")"
  if [[ -e "$config_path" || -L "$config_path" ]]; then
    if [[ -L "$config_path" || ! -f "$config_path" || \
          ! "${NGINX_CONFIG_SHA256:-}" =~ ^[0-9a-f]{64}$ ]]; then
      warn "Nginx configuration ownership could not be verified; preserving the connected services"
      return 1
    fi
    current_hash="$(sha256sum "$config_path" | awk '{print $1}')"
    if [[ "$current_hash" != "$NGINX_CONFIG_SHA256" ]]; then
      warn "Nginx configuration changed after deployment; preserving the connected services"
      return 1
    fi
  fi
  return 0
}

remove_xray() {
  (( XRAY_INSTALLED_BY_TOOL && ! PRESERVE_XRAY )) || return 0
  if ! xray_is_safe_to_remove; then
    PRESERVE_NGINX=1
    PRESERVE_TLS=1
    RETAINED_RESOURCES+=("Xray installation and configuration")
    return 0
  fi
  local installer_url installer
  installer_url="https://raw.githubusercontent.com/XTLS/Xray-install/${XRAY_INSTALLER_COMMIT}/install-release.sh"
  if [[ "${XHTTP_UNINSTALL_TEST_MODE:-0}" == 1 ]]; then
    log "test mode: skipped official Xray removal command"
    XRAY_REMOVED=1
    return 0
  else
    installer="${TMP_DIR}/install-release.sh"
    curl -fsSL "$installer_url" -o "$installer"
    bash "$installer" remove --purge
  fi
  rm -f /usr/local/bin/xray /etc/systemd/system/xray.service \
    /etc/systemd/system/xray@.service /etc/logrotate.d/xray
  rm -rf /etc/systemd/system/xray.service.d /etc/systemd/system/xray@.service.d \
    /usr/local/share/xray /var/log/xray
  systemctl daemon-reload
  XRAY_REMOVED=1
  if [[ "${XRAY_USER_CREATED_BY_TOOL:-0}" == 1 ]] && getent passwd xray >/dev/null; then
    userdel --system xray || warn "could not remove the tool-created xray user"
  fi
  if [[ "${XRAY_GROUP_CREATED_BY_TOOL:-0}" == 1 ]] && getent group xray >/dev/null; then
    groupdel xray || warn "could not remove the tool-created xray group"
  fi
}

remove_acme_lineage() {
  (( ACME_CERT_ISSUED_BY_TOOL )) || return 0
  local acme_path lineage_path domain
  domain="${ACME_DOMAIN:-}"
  [[ "$domain" =~ ^[A-Za-z0-9.-]+$ ]] || { warn "invalid ACME domain marker; preserving ACME data"; return 0; }
  acme_path="$(path_of "${ACME_HOME}/acme.sh")"
  lineage_path="$(path_of "${ACME_HOME}/${domain}_ecc")"
  if [[ -x "$acme_path" ]]; then
    "$acme_path" --remove -d "$domain" --ecc >/dev/null 2>&1 ||
      warn "acme.sh could not unregister the tool certificate lineage"
  fi
  rm -rf "$lineage_path"
  rm -f "$(path_of "${ACME_HOME}/${domain}_ecc.conf")"
}

has_other_acme_lineages() {
  local home_path file name domain="${ACME_DOMAIN:-}"
  home_path="$(path_of "$ACME_HOME")"
  [[ -d "$home_path" ]] || return 1
  shopt -s nullglob
  for file in "$home_path"/*.conf; do
    name="$(basename "$file")"
    case "$name" in
      account.conf|ca.conf|"${domain}_ecc.conf"|"${domain}.conf") ;;
      *) shopt -u nullglob; return 0 ;;
    esac
  done
  shopt -u nullglob
  return 1
}

remove_acme_cron() {
  local home_path="$1" crontab_file filtered_file
  [[ "${XHTTP_UNINSTALL_TEST_MODE:-0}" == 1 ]] && return 0
  command -v crontab >/dev/null 2>&1 || return 0
  crontab_file="${TMP_DIR}/root.crontab"
  filtered_file="${TMP_DIR}/root.crontab.filtered"
  if ! crontab -l > "$crontab_file" 2>"${TMP_DIR}/crontab.err"; then
    if [[ -s "${TMP_DIR}/crontab.err" ]] && ! grep -qi 'no crontab' "${TMP_DIR}/crontab.err"; then
      warn "could not inspect root crontab; preserving acme.sh installation"
      return 1
    fi
    return 0
  fi
  awk -v home="$home_path" 'index($0, home) && index($0, "--cron") { next } { print }' \
    "$crontab_file" > "$filtered_file"
  crontab "$filtered_file"
}

remove_acme_installation_if_exclusive() {
  if (( ! ACME_INSTALLED_BY_TOOL )); then
    if [[ -d "$(path_of "$ACME_HOME")" ]]; then
      PRESERVE_ACME=1
      RETAINED_RESOURCES+=("pre-existing acme.sh installation at ${ACME_HOME}")
    fi
    return 0
  fi
  local home_path
  home_path="$(path_of "$ACME_HOME")"
  [[ -d "$home_path" ]] || return 0
  if has_other_acme_lineages; then
    warn "acme.sh has other certificate lineages; preserving its installation and account data"
    PRESERVE_ACME=1
    RETAINED_RESOURCES+=("acme.sh at ${ACME_HOME}")
    return 0
  fi
  if ! remove_acme_cron "$ACME_HOME"; then
    PRESERVE_ACME=1
    RETAINED_RESOURCES+=("acme.sh at ${ACME_HOME} (root crontab could not be safely edited)")
    return 0
  fi
  rm -rf "$home_path"
  log "removed tool-installed acme.sh and its account data"
}

has_other_nginx_configs() {
  local confd sites file name
  confd="$(path_of /etc/nginx/conf.d)"
  sites="$(path_of /etc/nginx/sites-enabled)"
  shopt -s nullglob
  for file in "$confd"/*.conf; do
    [[ "$(basename "$file")" == "${APP_NAME}.conf" ]] && continue
    shopt -u nullglob
    return 0
  done
  for file in "$sites"/*; do
    name="$(basename "$file")"
    [[ "$name" == default ]] && continue
    shopt -u nullglob
    return 0
  done
  shopt -u nullglob
  return 1
}

installed_package_names() {
  dpkg-query -W -f='${binary:Package}\t${db:Status-Status}\n' 2>/dev/null |
    awk -F '\t' '$2 == "installed" { print $1 }' | sort -u
}

purge_owned_packages() {
  local baseline package plan planned external
  local -a packages planned_packages
  packages=()
  if [[ -n "${OWNED_PACKAGES:-}" ]]; then
    mapfile -t packages < <(printf '%s\n' "$OWNED_PACKAGES" | sed '/^$/d')
  else
    baseline="$(path_of "${PACKAGE_BASELINE_FILE:-${STATE_DIR}/packages.before}")"
    if [[ -f "$baseline" ]]; then
      mapfile -t packages < <(comm -13 "$baseline" <(installed_package_names))
    fi
  fi
  ((${#packages[@]})) || return 0

  if (( PRESERVE_ACME )) && printf '%s\n' "${packages[@]}" | grep -Eq '^cron($|-|:)'; then
    warn "acme.sh is being preserved; preserving newly installed Debian packages"
    RETAINED_RESOURCES+=("Debian packages: ${packages[*]}")
    return 0
  fi
  if (( PRESERVE_NGINX )) && printf '%s\n' "${packages[@]}" | grep -Eq '^nginx($|-|:)'; then
    warn "the tool Nginx configuration is modified; preserving newly installed Debian packages"
    RETAINED_RESOURCES+=("Debian packages: ${packages[*]}")
    return 0
  fi
  if has_other_nginx_configs && printf '%s\n' "${packages[@]}" | grep -Eq '^nginx($|-|:)'; then
    warn "other Nginx sites remain; preserving newly installed Debian packages"
    RETAINED_RESOURCES+=("Debian packages: ${packages[*]}")
    return 0
  fi
  if (( DRY_RUN )); then
    printf '[DRY-RUN] would simulate and purge packages: %s\n' "${packages[*]}"
    return 0
  fi

  plan="$(apt-get -s purge --no-auto-remove "${packages[@]}" 2>&1)" || {
    warn "could not simulate package removal; preserving newly installed packages"
    RETAINED_RESOURCES+=("Debian packages: ${packages[*]}")
    return 0
  }
  mapfile -t planned_packages < <(awk '/^(Remv|Purg) / { print $2 }' <<< "$plan" | sort -u)
  external=0
  for package in "${planned_packages[@]}"; do
    local owned match=0
    for owned in "${packages[@]}"; do
      if [[ "$owned" == "$package" ]]; then
        match=1
        break
      fi
    done
    (( match )) || external=1
  done
  if (( external )); then
    warn "package removal would affect packages not recorded as tool-installed; preserving all newly installed packages"
    RETAINED_RESOURCES+=("Debian packages: ${packages[*]}")
    return 0
  fi
  apt-get purge -y --no-auto-remove "${packages[@]}"
}

confirm_uninstall() {
  (( ASSUME_YES )) && return 0
  [[ -r /dev/tty ]] || die "interactive confirmation requires a terminal; use --yes to confirm explicitly"
  local answer
  read -r -p 'Type UNINSTALL to continue: ' answer </dev/tty
  [[ "$answer" == UNINSTALL ]] || die "uninstall cancelled"
}

main() {
  parse_args "$@"
  require_root
  if (( DRY_RUN )); then
    load_state
    show_plan
    printf '[DRY-RUN] no changes made\n'
    return 0
  fi
  command -v flock >/dev/null 2>&1 || die "flock is required"
  local lock_fd
  mkdir -p "$(dirname "$(path_of "$LOCK_FILE")")"
  exec {lock_fd}>"$(path_of "$LOCK_FILE")"
  flock -n "$lock_fd" || die "an update or uninstall is already running"
  load_state
  show_plan
  confirm_uninstall
  new_temp_dir
  trap '[[ -n "${TMP_DIR:-}" ]] && rm -rf "$TMP_DIR"' EXIT

  if ! nginx_is_safe_to_remove; then
    PRESERVE_XRAY=1
    PRESERVE_NGINX=1
    PRESERVE_TLS=1
    RETAINED_RESOURCES+=("Xray installation and configuration (used by the preserved Nginx configuration)")
    RETAINED_RESOURCES+=("Nginx configuration: ${NGINX_CONF_PATH}")
  fi
  if (( XRAY_INSTALLED_BY_TOOL && ! PRESERVE_XRAY )) && ! xray_is_safe_to_remove; then
    PRESERVE_XRAY=1
    PRESERVE_NGINX=1
    PRESERVE_TLS=1
    RETAINED_RESOURCES+=("Xray installation and configuration")
  fi

  remove_xray
  if (( XRAY_REMOVED )); then
    restore_or_remove_file "$XRAY_CONFIG_PATH" "${XRAY_CONFIG_BACKUP:-}" 1 "${XRAY_CONFIG_SHA256:-}"
    rmdir "$(path_of /usr/local/etc/xray)" 2>/dev/null || true
  fi

  if (( ! PRESERVE_NGINX )); then
    restore_or_remove_file "$NGINX_CONF_PATH" "${NGINX_CONFIG_BACKUP:-}" 1 "${NGINX_CONFIG_SHA256:-}"
    if (( FILE_PRESERVED )); then
      PRESERVE_NGINX=1
      PRESERVE_TLS=1
    fi
  fi
  restore_or_remove_file "$CLIENT_FILE" "${CLIENT_FILE_BACKUP:-}" "${CLIENT_FILE_CREATED_BY_TOOL:-1}" "${CLIENT_FILE_SHA256:-}"
  remove_acme_lineage
  remove_acme_installation_if_exclusive

  local site_index site_dir current_hash
  site_index="$(path_of "${SITE_DIR}/index.html")"
  site_dir="$(path_of "$SITE_DIR")"
  if (( PRESERVE_NGINX )); then
    RETAINED_RESOURCES+=("$site_dir (referenced by the preserved Nginx configuration)")
  else
    if [[ "${SITE_INDEX_CREATED_BY_TOOL:-0}" == 1 && -f "$site_index" ]]; then
      current_hash="$(sha256sum "$site_index" | awk '{print $1}')"
      if [[ -n "${SITE_INDEX_SHA256:-}" && "$current_hash" == "$SITE_INDEX_SHA256" ]]; then
        rm -f "$site_index"
      else
        warn "site index changed since deployment; preserving $site_index"
        RETAINED_RESOURCES+=("$site_index (changed after deployment)")
      fi
    fi
    if [[ "${SITE_DIR_CREATED_BY_TOOL:-0}" == 1 ]]; then
      if ! rmdir "$site_dir" 2>/dev/null; then
        warn "site directory contains user files; preserving $site_dir"
        RETAINED_RESOURCES+=("$site_dir (contains files not owned by this tool)")
      fi
    fi
  fi

  if (( ! PRESERVE_NGINX )) && systemctl is-active --quiet nginx 2>/dev/null; then
    systemctl reload nginx || warn "Nginx configuration was restored, but reload failed"
  fi
  purge_owned_packages

  local state_path backup_path tls_path
  state_path="$(path_of "$STATE_DIR")"
  backup_path="$(path_of "${STATE_DIR}/backups")"
  tls_path="$(path_of "${STATE_DIR}/tls")"
  rm -f "$(path_of "${STATE_DIR}/config.env")" \
    "$(path_of "${STATE_DIR}/install-state.env")" \
    "$(path_of "${STATE_DIR}/packages.before")"
  rm -f "$backup_path/config.json.original" \
    "$backup_path/${APP_NAME}.conf.original" \
    "$backup_path/client-v2rayn.txt.original"
  rmdir "$backup_path" 2>/dev/null || true
  if (( ! PRESERVE_TLS )); then
    rm -f "$tls_path/fullchain.pem" "$tls_path/privkey.pem"
    rmdir "$tls_path" 2>/dev/null || true
  else
    RETAINED_RESOURCES+=("TLS certificate copies at ${STATE_DIR}/tls (used by the preserved Nginx configuration)")
  fi
  rmdir "$state_path" 2>/dev/null || true
  rmdir "$(path_of "$CLIENT_DIR")" 2>/dev/null || true
  if ((${#RETAINED_RESOURCES[@]})); then
    local retained_path item
    retained_path="${state_path}/uninstall-retained.txt"
    install -d -m 700 "$state_path"
    {
      printf 'Some shared resources were retained for safety:\n'
      for item in "${RETAINED_RESOURCES[@]}"; do printf '%s\n' "$item"; done
    } > "$retained_path"
    chmod 600 "$retained_path"
    warn "some shared resources were retained; details: /etc/xhttp-cdn-deploy/uninstall-retained.txt"
  else
    log "uninstall completed"
  fi
}

main "$@"
