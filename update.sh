#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'
umask 077

APP_NAME="xhttp-cdn-deploy"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
. "${SCRIPT_DIR}/runtime-versions.sh"

STATE_DIR="/etc/${APP_NAME}"
INSTALL_STATE_FILE="${STATE_DIR}/install-state.env"
LOCK_FILE="/run/lock/${APP_NAME}.lock"
XRAY_BIN="/usr/local/bin/xray"
XRAY_CONFIG="/usr/local/etc/xray/config.json"
NGINX_CONFIG="/etc/nginx/conf.d/${APP_NAME}.conf"
ACME_HOME="/root/.acme.sh"
ACME_INSTALL_URL="https://get.acme.sh"
DEBIAN_PACKAGES=(ca-certificates curl cron jq nginx openssl unzip)

DRY_RUN=0
ASSUME_YES=0
TEST_ROOT="${XHTTP_UPDATE_TEST_ROOT:-}"
TMP_DIR=""
XRAY_VERSION=""
XRAY_INSTALL_REF=""
ACME_VERSION=""
XRAY_VERSION_RESOLVED=""
ACME_VERSION_RESOLVED=""
XRAY_VERSION_INSTALLED=""
ACME_VERSION_INSTALLED=""
NGINX_VERSION_INSTALLED=""
DEBIAN_PACKAGE_VERSIONS=""
COMPONENTS_UPDATED_UTC=""
XRAY_SERVICE_CUSTOM=0

log() { printf '[INFO] %s\n' "$*"; }
warn() { printf '[WARN] %s\n' "$*" >&2; }
die() { printf '[ERROR] %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'EOF'
Usage:
  sudo bash update.sh [--dry-run] [--yes]

Without --yes, the script asks for the word UPDATE before making changes.
Only Xray, acme.sh, Nginx, and this tool's Debian dependencies are updated.
EOF
}

parse_args() {
  while (($#)); do
    case "$1" in
      --dry-run) DRY_RUN=1 ;;
      --yes|-y) ASSUME_YES=1 ;;
      --help|-h) usage; exit 0 ;;
      *) usage >&2; die "unknown argument: $1" ;;
    esac
    shift
  done
}

path_of() {
  local value="$1"
  if [[ -n "$TEST_ROOT" ]]; then
    printf '%s%s' "${TEST_ROOT%/}" "$value"
  else
    printf '%s' "$value"
  fi
}

require_environment() {
  if [[ -n "$TEST_ROOT" ]]; then
    [[ "${XHTTP_UPDATE_TEST_MODE:-0}" == 1 ]] || die "test root is only available to the isolated test harness"
    [[ "$TEST_ROOT" == /* && "$TEST_ROOT" != / ]] || die "invalid test root"
  else
    (( EUID == 0 )) || die "run this script as root"
    [[ -r /etc/os-release ]] || die "cannot read /etc/os-release"
    # shellcheck disable=SC1091
    . /etc/os-release
    [[ "${ID:-}" == debian && "${VERSION_ID:-}" =~ ^(12|13)(\.|$) ]] ||
      die "only Debian 12 or Debian 13 is supported"
  fi
  local command_name
  for command_name in apt-get curl dpkg-query flock jq nginx sha256sum systemctl; do
    command -v "$command_name" >/dev/null 2>&1 || die "$command_name is required"
  done
}

load_state() {
  local state_path
  state_path="$(path_of "$INSTALL_STATE_FILE")"
  [[ -f "$state_path" && ! -L "$state_path" ]] || die "tool installation state is missing or not a regular file"
  if [[ -z "$TEST_ROOT" && "$(stat -c '%u' "$state_path")" != 0 ]]; then
    die "installation state is not owned by root"
  fi
  # This root-owned file is generated by deploy.sh using shell-escaped values.
  # shellcheck disable=SC1090
  . "$state_path"
  [[ "${STATE_VERSION:-}" == 3 ]] || die "this installation does not have the current update state; deploy the current package first"
  [[ "${XRAY_INSTALLED_BY_TOOL:-0}" == 1 ]] || die "Xray is not recorded as installed by this tool"
  [[ "${XRAY_INSTALLER_COMMIT:-}" =~ ^[0-9a-f]{40}$ ]] || die "invalid Xray installer commit in state"
  [[ "${XRAY_VERSION_RESOLVED:-}" =~ ^v[0-9]+(\.[0-9]+){1,3}$ ]] || die "invalid Xray version in state"
  [[ -n "${ACME_VERSION_RESOLVED:-}" ]] || die "invalid acme.sh version in state"
  [[ "${ACME_INSTALLED_BY_TOOL:-0}" =~ ^[01]$ ]] || die "invalid acme.sh ownership marker"
  XRAY_VERSION_RESOLVED="$XRAY_VERSION_RESOLVED"
  ACME_VERSION_RESOLVED="$ACME_VERSION_RESOLVED"
  XRAY_VERSION_INSTALLED="${XRAY_VERSION_INSTALLED:-}"
  ACME_VERSION_INSTALLED="${ACME_VERSION_INSTALLED:-unavailable}"
  NGINX_VERSION_INSTALLED="${NGINX_VERSION_INSTALLED:-}"
  DEBIAN_PACKAGE_VERSIONS="${DEBIAN_PACKAGE_VERSIONS:-}"
  COMPONENTS_UPDATED_UTC="${COMPONENTS_UPDATED_UTC:-}"
}

check_paths() {
  local path service_path service_hash data_path
  local -a required_paths
  required_paths=("$XRAY_BIN" "$XRAY_CONFIG" "$NGINX_CONFIG")
  for path in "${required_paths[@]}"; do
    path="$(path_of "$path")"
    [[ -f "$path" && ! -L "$path" ]] || die "required tool file is missing or unsafe: $path"
  done
  [[ -x "$(path_of "$XRAY_BIN")" ]] || die "Xray binary is not executable"
  data_path="$(path_of /usr/local/share/xray)"
  if [[ -e "$data_path" || -L "$data_path" ]]; then
    [[ -d "$data_path" && ! -L "$data_path" ]] || die "Xray data path is not a regular directory"
  fi
  [[ "${XRAY_BINARY_SHA256:-}" =~ ^[0-9a-f]{64}$ ]] || die "Xray binary ownership hash is missing"
  [[ -n "${XRAY_SERVICE_FILE:-}" ]] || die "Xray service file path is missing in installation state"
  service_path="$(path_of "$XRAY_SERVICE_FILE")"
  [[ -f "$service_path" && ! -L "$service_path" ]] || die "Xray service file is missing or unsafe"
  [[ "${XRAY_SERVICE_SHA256:-}" =~ ^[0-9a-f]{64}$ ]] || XRAY_SERVICE_CUSTOM=1
  if (( ! XRAY_SERVICE_CUSTOM )); then
    service_hash="$(sha256sum "$service_path" | awk '{print $1}')"
    [[ "$service_hash" == "$XRAY_SERVICE_SHA256" ]] || XRAY_SERVICE_CUSTOM=1
  fi
  local acme_path
  acme_path="$(path_of "${ACME_HOME}/acme.sh")"
  if [[ -e "$acme_path" || -L "$acme_path" ]]; then
    [[ -f "$acme_path" && ! -L "$acme_path" && -x "$acme_path" ]] ||
      die "acme.sh path is not a regular executable file"
  else
    log "acme.sh is not installed; it will be skipped"
  fi
  local package status
  for package in "${DEBIAN_PACKAGES[@]}"; do
    status="$(dpkg-query -W -f='${db:Status-Status}' "$package" 2>/dev/null || true)"
    [[ "$status" == installed ]] || die "required Debian package is not installed: $package"
  done
}

validate_configs() {
  "$(path_of "$XRAY_BIN")" run -test -config "$(path_of "$XRAY_CONFIG")" || {
    printf '[ERROR] current Xray configuration does not validate\n' >&2
    return 1
  }
  nginx -t || {
    printf '[ERROR] current Nginx configuration does not validate\n' >&2
    return 1
  }
}

xray_version_matches_target() {
  local reported="$1" expected="${XRAY_VERSION#v}"
  [[ "$reported" == "$expected" || "$reported" == "v$expected" ||
     "$reported" == "Xray $expected" || "$reported" == "Xray $expected "* ]]
}

capture_versions() {
  local xray_path acme_path
  xray_path="$(path_of "$XRAY_BIN")"
  acme_path="$(path_of "${ACME_HOME}/acme.sh")"
  XRAY_VERSION_INSTALLED="$("$xray_path" version 2>/dev/null | head -n1)"
  NGINX_VERSION_INSTALLED="$(nginx -v 2>&1)"
  DEBIAN_PACKAGE_VERSIONS="$(dpkg-query -W -f='${binary:Package}=${Version}\n' "${DEBIAN_PACKAGES[@]}" | sort)"
  if [[ -x "$acme_path" ]]; then
    ACME_VERSION_INSTALLED="$("$acme_path" --version 2>/dev/null | tail -n1)"
  else
    ACME_VERSION_INSTALLED="unavailable"
  fi
  COMPONENTS_UPDATED_UTC="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}

write_state() {
  local state_path temporary
  state_path="$(path_of "$INSTALL_STATE_FILE")"
  temporary="${state_path}.tmp"
  {
    printf 'STATE_VERSION=3\n'
    printf 'XRAY_INSTALLER_COMMIT=%q\n' "$XRAY_INSTALLER_COMMIT"
    printf 'XRAY_VERSION_RESOLVED=%q\n' "$XRAY_VERSION_RESOLVED"
    printf 'ACME_VERSION_RESOLVED=%q\n' "$ACME_VERSION_RESOLVED"
    printf 'XRAY_VERSION_INSTALLED=%q\n' "$XRAY_VERSION_INSTALLED"
    printf 'ACME_VERSION_INSTALLED=%q\n' "$ACME_VERSION_INSTALLED"
    printf 'NGINX_VERSION_INSTALLED=%q\n' "$NGINX_VERSION_INSTALLED"
    printf 'DEBIAN_PACKAGE_VERSIONS=%q\n' "$DEBIAN_PACKAGE_VERSIONS"
    printf 'COMPONENTS_UPDATED_UTC=%q\n' "$COMPONENTS_UPDATED_UTC"
    printf 'XRAY_INSTALLED_BY_TOOL=%q\n' "$XRAY_INSTALLED_BY_TOOL"
    printf 'XRAY_USER_CREATED_BY_TOOL=%q\n' "$XRAY_USER_CREATED_BY_TOOL"
    printf 'XRAY_GROUP_CREATED_BY_TOOL=%q\n' "$XRAY_GROUP_CREATED_BY_TOOL"
    printf 'XRAY_SERVICE_FILE=%q\n' "$XRAY_SERVICE_FILE"
    printf 'XRAY_SERVICE_SHA256=%q\n' "$XRAY_SERVICE_SHA256"
    printf 'XRAY_BINARY_SHA256=%q\n' "$XRAY_BINARY_SHA256"
    printf 'ACME_INSTALLED_BY_TOOL=%q\n' "$ACME_INSTALLED_BY_TOOL"
    printf 'ACME_CERT_ISSUED_BY_TOOL=%q\n' "$ACME_CERT_ISSUED_BY_TOOL"
    printf 'ACME_DOMAIN=%q\n' "$ACME_DOMAIN"
    printf 'OWNED_PACKAGES=%q\n' "$OWNED_PACKAGES"
    printf 'PACKAGE_BASELINE_FILE=%q\n' "$PACKAGE_BASELINE_FILE"
    printf 'XRAY_CONFIG_BACKUP=%q\n' "$XRAY_CONFIG_BACKUP"
    printf 'NGINX_CONFIG_BACKUP=%q\n' "$NGINX_CONFIG_BACKUP"
    printf 'CLIENT_FILE_BACKUP=%q\n' "$CLIENT_FILE_BACKUP"
    printf 'CLIENT_FILE_CREATED_BY_TOOL=%q\n' "$CLIENT_FILE_CREATED_BY_TOOL"
    printf 'SITE_DIR_CREATED_BY_TOOL=%q\n' "$SITE_DIR_CREATED_BY_TOOL"
    printf 'SITE_INDEX_CREATED_BY_TOOL=%q\n' "$SITE_INDEX_CREATED_BY_TOOL"
    printf 'SITE_INDEX_SHA256=%q\n' "$SITE_INDEX_SHA256"
    printf 'XRAY_CONFIG_SHA256=%q\n' "$XRAY_CONFIG_SHA256"
    printf 'NGINX_CONFIG_SHA256=%q\n' "$NGINX_CONFIG_SHA256"
    printf 'CLIENT_FILE_SHA256=%q\n' "$CLIENT_FILE_SHA256"
    printf 'REALITY_DOMAIN=%q\n' "$REALITY_DOMAIN"
  } > "$temporary"
  chmod 600 "$temporary"
  mv -f "$temporary" "$state_path"
}

confirm_update() {
  (( ASSUME_YES )) && return 0
  [[ -r /dev/tty ]] || die "interactive confirmation requires a terminal; use --yes to confirm explicitly"
  local answer
  read -r -p 'Type UPDATE to continue: ' answer </dev/tty
  [[ "$answer" == UPDATE ]] || die "update cancelled"
}

new_temp_dir() {
  local base="${TMPDIR:-/tmp}"
  TMP_DIR="$(mktemp -d "${base%/}/${APP_NAME}-update.XXXXXX")"
}

refresh_debian_packages() {
  export DEBIAN_FRONTEND=noninteractive
  apt-get update || return 1
  if ! apt-get install -y --only-upgrade --no-install-recommends "${DEBIAN_PACKAGES[@]}"; then
    capture_versions || true
    write_state || true
    warn "some Debian packages may have updated before apt reported failure; recorded installed versions"
    return 1
  fi
  capture_versions || return 1
  write_state || return 1
}

restart_nginx() {
  nginx -t || return 1
  systemctl restart nginx || return 1
  systemctl is-active --quiet nginx || return 1
}

refresh_acme() {
  local acme_path installer
  acme_path="$(path_of "${ACME_HOME}/acme.sh")"
  [[ -x "$acme_path" ]] || return 0
  installer="${TMP_DIR}/get-acme.sh"
  curl -fsSL --retry 2 --max-time 30 "$ACME_INSTALL_URL" -o "$installer" || {
    warn "could not download official acme.sh installer; stopping the update"
    return 1
  }
  if [[ "${XHTTP_UPDATE_TEST_MODE:-0}" == 1 ]]; then
    printf '%s\n' "$ACME_VERSION" > "$(path_of /root/.acme.sh/.test-version)"
  elif ! BRANCH="$ACME_VERSION" sh "$installer"; then
    warn "official acme.sh update failed"
    capture_versions || true
    write_state || true
    return 1
  fi
  rm -f "$installer"
  [[ -x "$acme_path" ]] || {
    warn "acme.sh disappeared during update"
    capture_versions || true
    write_state || true
    return 1
  }
  ACME_VERSION_INSTALLED="$("$acme_path" --version 2>/dev/null | tail -n1)"
  [[ "$ACME_VERSION_INSTALLED" == *"$ACME_VERSION"* ]] || {
    warn "acme.sh did not report the requested stable release $ACME_VERSION"
    capture_versions || true
    write_state || true
    return 1
  }
  ACME_VERSION_RESOLVED="$ACME_VERSION"
  capture_versions || { warn "could not record component versions after acme.sh update"; return 1; }
  write_state || { warn "could not write installation state after acme.sh update"; return 1; }
}

install_latest_xray() {
  local installer="${TMP_DIR}/install-release.sh"
  curl -fsSL --retry 2 --max-time 30 \
    "https://raw.githubusercontent.com/XTLS/Xray-install/${XRAY_INSTALL_REF}/install-release.sh" \
    -o "$installer" || { warn "could not download the official Xray installer"; return 1; }
  if [[ "${XHTTP_UPDATE_TEST_MODE:-0}" == 1 ]]; then
    printf '%s\n' "$XRAY_VERSION" > "$(path_of /usr/local/share/xray/.test-version)"
    printf 'xray-installer %s %s --no-update-service\n' "$XRAY_INSTALL_REF" "$XRAY_VERSION" >> "$XHTTP_UPDATE_TEST_CALL_LOG"
  elif ! bash "$installer" install -u root --version "$XRAY_VERSION" --no-update-service; then
    warn "official Xray installer failed"
    return 1
  fi
  rm -f "$installer"
}

rollback_xray() {
  local binary_path config_path nginx_path data_path
  binary_path="$(path_of "$XRAY_BIN")"
  config_path="$(path_of "$XRAY_CONFIG")"
  nginx_path="$(path_of "$NGINX_CONFIG")"
  data_path="$(path_of /usr/local/share/xray)"
  cp -a "${TMP_DIR}/xray.bin" "${binary_path}.rollback"
  mv -f "${binary_path}.rollback" "$binary_path"
  cp -a "${TMP_DIR}/xray.config" "$config_path"
  cp -a "${TMP_DIR}/nginx.config" "$nginx_path"
  rm -rf "$data_path"
  if [[ -d "${TMP_DIR}/xray.data" ]]; then
    cp -a "${TMP_DIR}/xray.data" "$data_path"
  fi
  if [[ -f "${TMP_DIR}/xray.service" ]]; then
    cp -a "${TMP_DIR}/xray.service" "${TMP_DIR}/xray.service.rollback"
    mv -f "${TMP_DIR}/xray.service.rollback" "$(path_of "$XRAY_SERVICE_FILE")"
  fi
  if [[ "${XHTTP_UPDATE_TEST_MODE:-0}" == 1 ]]; then
    cat "${TMP_DIR}/old-xray-version" > "$(path_of /usr/local/share/xray/.test-version)"
  fi
  systemctl daemon-reload || true
  systemctl restart xray || warn "Xray rollback completed, but the previous service did not restart"
  warn "restored the previous Xray binary and tool configuration"
}

refresh_xray() {
  local binary_path config_path nginx_path service_path data_path old_version new_service
  binary_path="$(path_of "$XRAY_BIN")"
  config_path="$(path_of "$XRAY_CONFIG")"
  nginx_path="$(path_of "$NGINX_CONFIG")"
  data_path="$(path_of /usr/local/share/xray)"
  service_path="${XRAY_SERVICE_FILE:-}"
  [[ -n "$service_path" ]] || { warn "Xray service file path is missing in installation state"; return 1; }
  service_path="$(path_of "$service_path")"
  old_version="$XRAY_VERSION_INSTALLED"
  cp -a "$binary_path" "${TMP_DIR}/xray.bin"
  cp -a "$config_path" "${TMP_DIR}/xray.config"
  cp -a "$nginx_path" "${TMP_DIR}/nginx.config"
  if [[ -d "$data_path" && ! -L "$data_path" ]]; then
    cp -a "$data_path" "${TMP_DIR}/xray.data"
  elif [[ -e "$data_path" || -L "$data_path" ]]; then
    warn "Xray data directory is not a regular directory"
    return 1
  fi
  if [[ -f "$service_path" && ! -L "$service_path" ]]; then
    cp -a "$service_path" "${TMP_DIR}/xray.service"
  fi
  printf '%s\n' "$old_version" > "${TMP_DIR}/old-xray-version"

  systemctl stop xray || { warn "could not stop Xray before update"; return 1; }
  if ! install_latest_xray; then
    rollback_xray
    return 1
  fi
  if ! cmp -s "${TMP_DIR}/xray.config" "$config_path"; then
    cp -a "${TMP_DIR}/xray.config" "$config_path"
  fi
  if ! cmp -s "${TMP_DIR}/nginx.config" "$nginx_path"; then
    cp -a "${TMP_DIR}/nginx.config" "$nginx_path"
  fi
  if (( XRAY_SERVICE_CUSTOM )); then
    cp -a "${TMP_DIR}/xray.service" "${TMP_DIR}/xray.service.restore"
    mv -f "${TMP_DIR}/xray.service.restore" "$service_path"
  fi
  if [[ "${XHTTP_UPDATE_TEST_MODE:-0}" == 1 ]]; then
    XRAY_VERSION_INSTALLED="$(cat "$(path_of /usr/local/share/xray/.test-version)")"
  else
    XRAY_VERSION_INSTALLED="$("$binary_path" version 2>/dev/null | head -n1)"
  fi
  xray_version_matches_target "$XRAY_VERSION_INSTALLED" || {
    warn "installed Xray version does not match latest stable release $XRAY_VERSION"
    rollback_xray
    return 1
  }
  if ! validate_configs || ! systemctl daemon-reload || ! systemctl restart xray ||
     ! systemctl is-active --quiet xray; then
    warn "updated Xray failed validation or did not start"
    rollback_xray
    return 1
  fi

  XRAY_VERSION_RESOLVED="$XRAY_VERSION"
  XRAY_INSTALLER_COMMIT="$XRAY_INSTALL_REF"
  XRAY_BINARY_SHA256="$(sha256sum "$binary_path" | awk '{print $1}')"
  new_service="$(systemctl show --property=FragmentPath --value xray.service 2>/dev/null || true)"
  if [[ -n "$new_service" && "$new_service" != "$XRAY_SERVICE_FILE" ]]; then
    warn "Xray service file path changed during update"
    rollback_xray
    return 1
  fi
  if [[ -n "$new_service" ]]; then
    XRAY_SERVICE_FILE="$new_service"
    new_service="$(path_of "$XRAY_SERVICE_FILE")"
    if (( ! XRAY_SERVICE_CUSTOM )) && [[ -f "$new_service" && ! -L "$new_service" ]]; then
      XRAY_SERVICE_SHA256="$(sha256sum "$new_service" | awk '{print $1}')"
    fi
  fi
  if ! capture_versions || ! write_state; then
    warn "could not record component versions after Xray update"
    rollback_xray
    return 1
  fi
}

main() {
  parse_args "$@"
  require_environment
  if (( ! DRY_RUN )); then
    mkdir -p "$(dirname "$(path_of "$LOCK_FILE")")"
    exec {UPDATE_LOCK_FD}>"$(path_of "$LOCK_FILE")"
    flock -n "$UPDATE_LOCK_FD" || die "another update or uninstall is already running"
  fi
  load_state
  check_paths
  resolve_latest_versions || die "could not resolve latest official component versions"
  validate_configs || die "fix the current configuration before updating"
  printf 'Latest stable targets:\n'
  printf '  Xray:       %s\n' "$XRAY_VERSION"
  printf '  acme.sh:    %s\n' "$ACME_VERSION"
  printf '  Xray installer commit: %s\n' "$XRAY_INSTALL_REF"
  printf '  Debian:     latest candidates from configured Debian repositories\n'
  if (( DRY_RUN )); then
    printf '[DRY-RUN] no changes made\n'
    return 0
  fi
  confirm_update
  new_temp_dir
  trap '[[ -n "${TMP_DIR:-}" ]] && rm -rf "$TMP_DIR"' EXIT

  XRAY_VERSION_RESOLVED="$XRAY_VERSION"
  XRAY_INSTALLER_COMMIT="$XRAY_INSTALL_REF"
  ACME_VERSION_RESOLVED="$ACME_VERSION"
  write_state || die "could not record resolved component versions before updating"

  refresh_debian_packages || die "Debian dependency update failed"
  restart_nginx || die "Nginx configuration or service failed after Debian package update"
  refresh_acme || die "acme.sh update failed; Debian package updates remain applied"
  refresh_xray || die "Xray update failed; previous Xray binary was restored when possible"
  nginx -t || die "Nginx configuration failed after component update"
  log "component update completed"
  printf 'Recorded versions are in %s\n' "${INSTALL_STATE_FILE}"
}

if [[ "${XHTTP_UPDATE_LIBRARY_MODE:-0}" != 1 ]]; then
  main "$@"
fi
